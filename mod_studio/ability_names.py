def resolve_ability_name(ability_id: int, live_names: "dict | None" = None) -> str:
    """
    Prefers the mod loader's own live AbilityData.xml names (freshest, and
    self-corrects if the loader adds/renames abilities), falling back to
    this static FFTPatcher table, then an honest placeholder for anything
    neither source recognizes.
    """
    if ability_id == 0:
        return "(None)"
    if live_names and ability_id in live_names:
        return live_names[ability_id]
    return ABILITY_NAMES.get(ability_id, f"(Unrecognized Ability {ability_id})")


def resolve_ability_names(ability_ids: list, live_names: "dict | None" = None) -> list:
    return [resolve_ability_name(i, live_names) for i in ability_ids]
